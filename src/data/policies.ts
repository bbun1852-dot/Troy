import type { Region, Employment } from './regions'

export type PolicyCategory =
  | 'finance' // 자산·세제
  | 'housing' // 주거
  | 'job' // 일자리·창업
  | 'education' // 교육·역량
  | 'welfare' // 복지·생활
  | 'health' // 건강

export interface Policy {
  id: string
  category: PolicyCategory
  title: string
  /** 한 줄 요약 */
  summary: string
  /** 지금 할 실행 스텝 */
  action: string
  tag: string
  /** 공식 안내/신청 포털 URL (바로가기) */
  link: string
  /** 링크 라벨 (없으면 기본 '바로가기') */
  linkLabel?: string
  /** 자격: 최소/최대 나이 (없으면 제한 없음) */
  minAge?: number
  maxAge?: number
  /** 자격: 연봉 상한/하한 (만원, 없으면 제한 없음) */
  minSalary?: number
  maxSalary?: number
  /** 적용 지역(시·도). 없으면 전국 공통 */
  regions?: Region[]
  /** 해당하는 취업·활동 상태. 없으면 상태 무관 */
  employment?: Employment[]
  /** 무주택자 대상 여부 */
  requiresNoHome?: boolean
  /** 카테고리 내 우선순위(작을수록 먼저) */
  priority: number
}

